const assert = require('node:assert/strict');
const W = require('../assets/workflow.js');
const t = value => new Date(`2026-09-22T${value}-05:00`).getTime();
const s = W.create(), other = W.create();
const event = (time, pressure = 750) => W.advance(s, 'normal', t(time), pressure);
event('04:00:00', null);
assert.equal(event('04:30:00', 0).pressure, 0);
event('05:00:00');
assert.equal(s.stage, 'hold75');
assert.equal(W.deadline(s), t('05:30:00'));
assert.doesNotThrow(() => W.advance(structuredClone(s), 'normal', t('05:29:59'), null));
const restored = JSON.parse(JSON.stringify(s));
assert.equal(W.deadline(restored), t('05:30:00'), 'refresh retains hold start');
assert.equal(s.stage, 'hold75', 'reading a deadline never changes stage');
event('06:20:00');
assert.equal(s.stage, 'finalRamp', 'extended hold ends at operator-selected time');
W.setBaseline(s, t('06:20:00'), 750, 1234, .0043);
assert.equal(W.observe(s, {at: t('06:21:00'), pressure: 771}), 2);
assert.equal(W.observe(s, {at: t('06:21:02'), pressure: 755}), 0);
assert.equal(W.observe(s, {at: t('06:21:04'), pressure: 771}), 0, 'threshold fluctuation does not repeat alerts');
assert.throws(() => W.saveStroke(s, 770, 1250, t('06:21:00'), 771), /order/);
const row = W.saveStroke(s, 760, 1244, t('06:20:50'), 760);
assert.equal(row.strokes, 10); assert.ok(Math.abs(row.gallons - .043) < 1e-9);
assert.throws(() => W.saveStroke(s, 770, 1200, t('06:21:00'), 771), /cannot decrease/);
W.saveStroke(s, 770, 1254, t('06:21:00'), 771);
event('07:05:00', 1000);
assert.equal(W.deadline(s), t('07:30:00'));
assert.doesNotThrow(() => W.advance(structuredClone(s), 'normal', t('07:20:00'), 1000));
assert.doesNotThrow(() => W.advance(structuredClone(s), 'normal', t('07:31:00'), 1000));
assert.equal(W.nextStart(s, t('07:30:04')), t('07:30:04'));
event('07:30:00', 1000);
assert.equal(W.officialTimes(s, t('07:44:59')).length, 1);
assert.equal(W.officialTimes(s, t('07:45:00')).length, 2);
assert.equal(W.deadline(s), t('15:30:00'));
assert.doesNotThrow(() => W.advance(structuredClone(s), 'normal', t('15:29:59'), 998));
event('15:30:00', 998);
assert.equal(W.officialTimes(s, t('17:00:00')).length, 33);
assert.equal(W.deadline(s), t('15:45:00'));
assert.equal(s.stage, 'endHold');
assert.doesNotThrow(() => W.advance(structuredClone(s), 'normal', t('15:40:00'), 998));
event('17:00:00', 998);
assert.equal(s.officialEnd, t('15:30:00'), 'waiting for engineer does not extend the official test');
event('17:30:00', 0); assert.equal(s.stage, 'complete');
assert.equal(other.stage, 'pretest', 'tests have independent state');
const fresh = W.archive(s, {events: [{type: 'note', label: 'example'}], sheet: {spreadsheetId: 'old-sheet'}}, t('18:00:00'), 'Retest requested');
assert.equal(fresh.attempt, 2); assert.equal(fresh.officialStart, 0);
assert.equal(fresh.archives[0].officialEnd, t('15:30:00'));
assert.equal(fresh.archives[0].events.length, 1);
assert.equal(fresh.archives[0].strokes.length, 2);
assert.equal(fresh.archives[0].sheet.spreadsheetId, 'old-sheet');
assert.deepEqual(W.steps('half'), [0,50,75,100]);
assert.deepEqual(W.steps('staged'), [0,25,50,75,100]);
assert.throws(() => W.sheetCapacity({preTestRows: Array(5).fill({})}), /No rows were merged/);
assert.throws(() => W.sheetCapacity({officialRows: Array(34).fill({})}), /room for 33/);
assert.equal(W.nextQuarter(t('23:55:00')), new Date('2026-09-23T00:00:00-05:00').getTime());
const legacy = W.create({events: [{type:'ramp', label:'75% pressure checkpoint',at:t('05:00:00')}]});
assert.equal(legacy.stage,'hold75'); assert.equal(W.deadline(legacy),t('05:30:00'));
console.log('Workflow: extended holds, quarter-hours, restart history, independent tests, stroke counts and template capacity passed.');
