const assert = require('node:assert/strict');
const W = require('../assets/workflow.js');
const start=Date.UTC(2026,9,6,11,5), s=W.create();
W.recordEvent(s,'25',start,null); W.recordEvent(s,'hold-start',start+1000,null,'25% leak check');
W.recordEvent(s,'hold-end',start+123000,null,'25% leak check');
W.recordEvent(s,'50',start+124000,500); W.recordEvent(s,'75',start+125000,750);
W.advance(s,'staged',start+126000,null); assert.equal(s.stage,'finalRamp','No hold interlock');
W.advance(s,'staged',start+127000,1000); W.advance(s,'staged',start+128000,1000);
assert.equal(s.stage,'official','No quarter-hour or full hold lock');
const late=W.recordEvent(s,'25',start,250); assert.equal(late.pressure,250); assert.equal(s.stage,'official','Late checkpoint does not rewind test');
W.recordEvent(s,'end',start+130000,null); assert.equal(s.officialEnd,start+130000,'Actual end not blocked by eight-hour timer');
W.advance(s,'staged',start+130001,null); assert.equal(s.stage,'depressurizing');
W.advance(s,'staged',start+130002,null); assert.equal(s.stage,'complete');
const direct=W.create(); W.recordEvent(direct,'start',start,null); assert.equal(direct.stage,'official','Can start without clicking prior steps');
assert.throws(()=>W.recordEvent(direct,'end',start-1,0),/start/);
W.recordEvent(direct,'end',start+8*3600000,null);
W.recordEvent(direct,'start',start-60000,null); assert.equal(direct.officialStart,start-60000,'Correct official time');
assert.equal(W.recordEvent(W.create(),'hold-start',start,null).pressure,null,'Missing pressure not zero');
console.log('Flexible workflow: arbitrary holds, direct start/end, late/corrected entries, no timing gates, missing measurements preserved.');
