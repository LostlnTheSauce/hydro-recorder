const assert = require('node:assert/strict');
const {describe} = require('../assets/field-power.js');
const now = 100000;
const device = {bridge_online:true,power:{reported_at:now,battery_percent:84,on_ac:true,charging:true,has_battery:true}};
assert.match(describe(device,now).text,/84%.*Plugged in.*Charging/);
device.power.charging=false;
assert.match(describe(device,now).text,/Not charging/);
device.power.battery_percent=0;device.power.on_ac=false;
assert.equal(describe(device,now).state,'low');
device.power.battery_percent=null;
assert.equal(describe(device,now).state,'current');
assert.match(describe(device,now).text,/unknown/);
device.power.has_battery=false;device.power.on_ac=true;
assert.match(describe(device,now).text,/No battery detected/);
device.bridge_online=false;
assert.equal(describe(device,now).state,'stale');
device.bridge_online=true;device.power.reported_at=now-31000;
assert.equal(describe(device,now).state,'stale');
device.power={reported_at:now,battery_percent:90,on_ac:true,charging:true,has_battery:true,laptop_temp_f:142};
assert.match(describe(device,now).text,/90%.*Charging · 142 °F$/);
assert.equal(describe(device,now).state,'current');
device.power.laptop_temp_f=185;
assert.equal(describe(device,now).state,'low');
assert.match(describe(device,now).text,/185 °F · Too hot/);
device.power.has_battery=false;
assert.match(describe(device,now).text,/No battery detected · 185 °F · Too hot/);
assert.equal(describe({bridge_online:true},now).state,'unknown');
assert.equal(describe(null,now).state,'unknown');
const {batteryRun}=require('../assets/field-power.js');
const fmt=(at)=>`t${at/60000}`;
assert.equal(batteryRun({history:[]},0,fmt),'');
assert.equal(batteryRun({history:[{at:0,percent:100,on_ac:true}]},0,fmt),'');
const run={history:[{at:0,percent:100,on_ac:true},{at:60000,percent:100,on_ac:false},{at:600000,percent:90,on_ac:false}],reported_at:3*3600000,battery_percent:80};
assert.equal(batteryRun(run,3*3600000,fmt),'On battery since t1 at 100% · now at 80% (2 h 59 min).');
assert.equal(batteryRun(run,9*3600000,fmt),'Battery run: t1 at 100% until last heard from t180 at 80% (2 h 59 min).');
run.history.push({at:4*3600000,percent:3,on_ac:true});
assert.equal(batteryRun(run,5*3600000,fmt),'Last battery run: t1 at 100% until plugged in t240 at 3% (3 h 59 min).');
console.log('Power display passed: charging, plugged in/not charging, low/zero/unknown battery, desktop, stale, old bridge and laptop temperature.');
